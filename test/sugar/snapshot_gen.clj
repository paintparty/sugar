(ns sugar.snapshot-gen
  "Rewrites test/sugar/snapshots.cljc from the current output of every case in
   sugar.snapshot-cases. Run with `bb test:snapshot`, then review the diff."
  (:require [clojure.string :as str]
            [sugar.snapshot-cases :as cases]))

(def ^:private out-path "test/sugar/snapshots.cljc")

(defn- lit
  "pr-str, with ESC written as \\u001b so the file shows the codes."
  [v]
  (str/replace (pr-str v) "\u001b" "\\u001b"))

(defn- entry
  "One case as text: the id, then its output map with one key per line and the
   values aligned."
  [{:keys [id] :as c}]
  (let [m     (cases/run c)
        ks    (filter #(contains? m %) [:result :browser :printed])
        width (apply max (map #(count (str %)) ks))
        pad   #(apply str % (repeat (- width (count (str %))) " "))]
    (str "   " (lit id) "\n"
         "   {"
         (str/join "\n    "
                   (for [k ks]
                     (str (pad k) " " (lit (get m k)))))
         "}")))

(defn -main [& _]
  (let [ids (map :id cases/cases)]
    (when-let [dupes (seq (for [[id n] (frequencies ids) :when (> n 1)] id))]
      (throw (ex-info (str "Duplicate case ids: " (str/join ", " dupes)) {}))))
  (spit out-path
        (str ";; GENERATED by `bb test:snapshot` from test/sugar/snapshot_cases.cljc.\n"
             ";; Do not edit by hand.\n"
             "(ns sugar.snapshots)\n\n"
             "(def snapshots\n"
             "  {\n"
             (str/join "\n\n" (map entry cases/cases))
             "})\n"))
  (println "Wrote" out-path "with" (count cases/cases) "cases")
  (shutdown-agents))
